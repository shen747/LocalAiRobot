#!/usr/bin/env bash
# create_enrollments.sh -- scan a folder of NAMED face photos and (re)generate a batch script that enrols
# everyone into Concierge Mode via ./scripts/enroll_person.sh. Run on YOUR PC; it only reads filenames.
#
# AMEND-SAFE / IDEMPOTENT: if the output script already exists, re-running UPDATES it -- it keeps the
# descriptions you've already edited, adds lines for NEW people (with a <FILL THE DESC> placeholder), and
# refreshes each person's photo list. So: drop new photos into the folder, re-run, fill only the new blanks.
#
# Photos are grouped by PERSON = the filename stem minus any trailing _<number>:
#   Shanika.jpg Shanika_02.jpg Shanika_04.jpg  ->  one "Shanika" with all three
#   Rochelle.jpg Rochelle_2.jpg                ->  one "Rochelle" with both      ·   Mr.Silva.jpg -> "Mr.Silva"
#
# The generated paths point at ~/<folder> ON THE PI (scp the photos there). The generator is committed; its
# OUTPUT (enroll_all.sh) is git-ignored (personal names + descriptions).
#
#   ./scripts/create_enrollments.sh                              # default folder -> enroll_all.sh
#   ./scripts/create_enrollments.sh ../people_named enroll_all.sh  # explicit scan dir + output
#
# WORKFLOW: 1) run this  2) edit the "<FILL THE DESC>" lines  3) scp the photos + script to the Pi
#           4) run it on the Pi:  cd ~/LocalAiRobot && bash enroll_all.sh
set -uo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
# Default folder: the SIBLING people_named next to the repo (kept OUT of git), else the in-repo copy.
DEFAULT_SCAN="$(cd "$REPO/.." && pwd)/people_named"
[ -d "$DEFAULT_SCAN" ] || DEFAULT_SCAN="$REPO/people/people_named"
SCAN_DIR="${1:-$DEFAULT_SCAN}"
OUT="${2:-$REPO/enroll_all.sh}"
TARGET="~/$(basename "$SCAN_DIR")"      # where the photos live ON THE PI (literal ~ expands at run time)

[ -d "$SCAN_DIR" ] || { echo "scan dir not found: $SCAN_DIR  (pass it as arg 1)" >&2; exit 1; }

# Any working python3 (stdlib only -- no venv, no camera). Skip a broken 'python' shim (e.g. Windows Store).
PY=""
for cand in python3 python; do
  if command -v "$cand" >/dev/null 2>&1 && "$cand" -c '' >/dev/null 2>&1; then PY="$cand"; break; fi
done
[ -n "$PY" ] || { echo "python3 not found (needed to generate the script). In WSL: sudo apt install python3." >&2; exit 1; }

"$PY" - "$SCAN_DIR" "$OUT" "$TARGET" <<'PYEOF'
import os, re, sys
scan_dir, out, target = sys.argv[1], sys.argv[2], sys.argv[3]
PLACEHOLDER = "<FILL THE DESC>"

# 1) scan photos -> person (stem minus a trailing _<digits>) -> sorted basenames.
people = {}
for f in sorted(os.listdir(scan_dir)):
    if not os.path.isfile(os.path.join(scan_dir, f)):
        continue
    ext = f.rsplit(".", 1)[-1].lower() if "." in f else ""
    if ext not in ("jpg", "jpeg", "png"):
        continue
    name = re.sub(r"_\d+$", "", f.rsplit(".", 1)[0])   # strip trailing _NN -> person name
    people.setdefault(name, []).append(f)
if not people:
    sys.stderr.write(f"no .jpg/.jpeg/.png files in {scan_dir}\n"); sys.exit(1)
for n in people:
    people[n].sort()

# 2) preserve EDITED descriptions from an existing generated script (amend, don't clobber). Matches the two
#    quoted fields (Name, desc) after enroll_person.sh, tolerating leading flags/counts (--replace, --camera N).
descs = {}
if os.path.exists(out):
    with open(out, encoding="utf-8") as fh:
        for line in fh:
            m = re.search(r'enroll_person\.sh\s+(?:--\S+\s+|\d+\s+)*"([^"]*)"\s+"([^"]*)"', line)
            if m:
                descs[m.group(1)] = m.group(2)

# 3) write the script: reuse a known person's description, PLACEHOLDER for new ones.
new = sorted(n for n in people if n not in descs)
lines = [
    "#!/usr/bin/env bash",
    "# AUTO-GENERATED by scripts/create_enrollments.sh -- AMEND-SAFE (re-run to add new people; your edited",
    f"# descriptions are kept). DO NOT COMMIT (git-ignored). Photos live at {target}/ on the Pi.",
    f"#   run on the Pi:  cd ~/LocalAiRobot && bash {os.path.basename(out)}",
    "# enroll_person.sh REPLACES each person (idempotent), so re-running gives the same result -- no duplicates.",
    "set -uo pipefail",
    'cd "$(dirname "$0")"   # repo root (scp this file into ~/LocalAiRobot)',
    "",
]
for name in sorted(people, key=str.lower):
    desc = descs.get(name, PLACEHOLDER)
    paths = " ".join(f"{target}/{b}" for b in people[name])
    lines.append(f'./scripts/enroll_person.sh "{name}" "{desc}" {paths}')
lines += ["", "echo", 'echo ">> Enrolled Concierge faces:"', "./scripts/rag.sh --faces", ""]

with open(out, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
os.chmod(out, 0o755)

n_photos = sum(len(v) for v in people.values())
print(f">> wrote {out}")
print(f"   {len(people)} people, {n_photos} photos, from {scan_dir}  (paths -> {target}/ on the Pi)")
if descs:
    kept = sum(1 for n in people if n in descs)
    tail = (": " + ", ".join(new)) if new else "."
    print(f"   kept {kept} existing description(s); {len(new)} NEW need a description{tail}")
else:
    print(f"   all {len(people)} need a description (edit the <FILL THE DESC> lines).")
print("   NEXT: edit the <FILL THE DESC> lines, then scp the photos + this script to the Pi and run it.")
PYEOF
