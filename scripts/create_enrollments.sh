#!/usr/bin/env bash
# create_enrollments.sh -- scan a folder of NAMED face photos and GENERATE a single batch script that enrols
# everyone into Concierge Mode via ./scripts/enroll_person.sh. Run this on YOUR PC; it only reads filenames
# (no Python, no camera). Committed to the repo; the script it GENERATES is git-ignored (personal).
#
# Photos are grouped by PERSON = the filename stem minus any trailing _<number>, so:
#   Shanika.jpg Shanika_02.jpg Shanika_04.jpg  ->  one "Shanika" with all three photos
#   Rochelle.jpg Rochelle_2.jpg                ->  one "Rochelle" with both
#   Mr.Silva.jpg                               ->  "Mr.Silva"
#
# Each generated line uses --replace (clears that person's old embeddings first), so re-running the generated
# script is IDEMPOTENT -- the folder is the source of truth, no piling up duplicates. The generated paths point
# at ~/<folder> ON THE PI (scp the photos there); it ends by printing ./scripts/rag.sh --faces.
#
#   ./scripts/create_enrollments.sh                                   # scan people/people_named -> enroll_all.sh
#   ./scripts/create_enrollments.sh people/people_named enroll_all.sh # explicit scan dir + output file
#
# WORKFLOW: 1) run this   2) edit the "<FILL THE DESC>" for each person in the generated script
#           3) scp the photos + the generated script to the Pi   4) run it on the Pi from the repo root.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
SCAN_DIR="${1:-$REPO/people/people_named}"
OUT="${2:-$REPO/enroll_all.sh}"
TARGET="~/$(basename "$SCAN_DIR")"      # where the photos live ON THE PI (literal ~ expands at run time)

[ -d "$SCAN_DIR" ] || { echo "scan dir not found: $SCAN_DIR" >&2; exit 1; }

# Group image files by person (stem minus a trailing _<digits>). Bash assoc-array: name -> newline list.
declare -A PHOTOS
n_photos=0
shopt -s nullglob
for f in "$SCAN_DIR"/*; do
  [ -f "$f" ] || continue
  b="$(basename "$f")"
  ext="$(printf '%s' "${b##*.}" | tr '[:upper:]' '[:lower:]')"
  case "$ext" in jpg|jpeg|png) ;; *) continue ;; esac
  name="$(printf '%s' "${b%.*}" | sed -E 's/_[0-9]+$//')"   # strip trailing _NN -> person name
  PHOTOS["$name"]+="$b"$'\n'
  n_photos=$((n_photos + 1))
done
shopt -u nullglob

[ "${#PHOTOS[@]}" -gt 0 ] || { echo "no .jpg/.jpeg/.png files in $SCAN_DIR" >&2; exit 1; }

{
  echo "#!/usr/bin/env bash"
  echo "# AUTO-GENERATED by scripts/create_enrollments.sh on $(date +%Y-%m-%d) from ${SCAN_DIR#"$REPO"/}."
  echo "# DO NOT COMMIT (git-ignored). EDIT each \"<FILL THE DESC>\" relationship, then run ON THE PI:"
  echo "#   scp ${SCAN_DIR#"$REPO"/}/*  pi@<host>:$TARGET/          # the photos"
  echo "#   scp $(basename "$OUT")  pi@<host>:~/LocalAiRobot/       # this script"
  echo "#   ssh pi@<host> 'cd ~/LocalAiRobot && bash $(basename "$OUT")'"
  echo "# IDEMPOTENT: --replace clears each person's old embeddings first, so re-running gives the same result."
  echo "set -uo pipefail"
  echo "cd \"\$(dirname \"\$0\")\"   # run from the repo root (scp this file into ~/LocalAiRobot)"
  echo
  # people alphabetical; each person's photos sorted (base then _02, _03, ...).
  while IFS= read -r name; do
    paths=""
    while IFS= read -r b; do
      [ -n "$b" ] || continue
      paths+=" $TARGET/$b"
    done < <(printf '%s' "${PHOTOS[$name]}" | sort)
    printf './scripts/enroll_person.sh --replace "%s" "<FILL THE DESC>"%s\n' "$name" "$paths"
  done < <(printf '%s\n' "${!PHOTOS[@]}" | sort)
  echo
  echo 'echo'
  echo 'echo ">> Enrolled Concierge faces:"'
  echo './scripts/rag.sh --faces'
} > "$OUT"
chmod +x "$OUT"

echo ">> wrote $OUT"
echo "   ${#PHOTOS[@]} people, $n_photos photos, from $SCAN_DIR"
echo "   photos referenced as $TARGET/<file> -- scp them to the Pi there."
echo "   NEXT: edit the <FILL THE DESC> placeholders in $(basename "$OUT"), then scp + run it on the Pi."
