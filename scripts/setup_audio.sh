#!/usr/bin/env bash
# setup_audio.sh -- point ALSA's DEFAULT output at your USB speaker, the one-command way.
#
# WHY: the robot's VOICE (Piper -> `aplay` with no -D) plays to ALSA's *default* device. On Pi OS Lite
# the default is often the wrong card (HDMI, or the USB mic), so `aplay` fails with "audio open error:
# Unknown error 524" / you hear nothing. The fix is a ~/.asoundrc that makes the USB speaker the default.
# This script writes that file for you: it finds your USB *playback* card, makes it the default, sets a
# sane volume and persists it. Re-runnable; backs up any ~/.asoundrc you already had.
#
#   ./scripts/setup_audio.sh             auto-detect the USB speaker (works if there's exactly one)
#   ./scripts/setup_audio.sh UACDemoV10  use a specific card id (the name after 'card N:' in `aplay -l`)
#
# It ALSO writes the matching device names into config/robot.env (ROBOT_SOUNDS_DEVICE / ROBOT_MIC /
# ROBOT_WAKEWORD_DEVICE), by name, so you never hand-edit them. Idempotent -- a re-run rewrites the same
# values and keeps each line's comment (hand-tuned one? a re-run re-detects and overwrites it).
# scripts/cleanup_pi.sh removes the ~/.asoundrc this writes (restoring any backup).
set -uo pipefail

MARKER="# LocalAiRobot: default audio device (generated by scripts/setup_audio.sh)"
ASOUND="$HOME/.asoundrc"

case "${1:-}" in
  -h|--help)
    echo "usage: $(basename "$0") [SPEAKER_CARD_ID]   (id from 'aplay -l'; auto-detected if omitted)"
    exit 0 ;;
esac

# Writing ~/.asoundrc as root would target root's home, not yours -- refuse.
if [ "${EUID:-$(id -u)}" -eq 0 ]; then
  echo "Run as your normal user (not root/sudo): it writes ~/.asoundrc in YOUR home." >&2
  exit 1
fi
command -v aplay >/dev/null 2>&1 || { echo "alsa-utils not installed -- run scripts/install_stack.sh first." >&2; exit 1; }

# A card is "USB" iff /proc/asound/card<N>/usbid exists. Collect USB *playback* cards from `aplay -l`,
# whose lines look like:  card 2: UACDemoV10 [UACDemoV10], device 0: USB Audio [USB Audio]
usb_playback_ids() {
  aplay -l 2>/dev/null | sed -n 's/^card \([0-9]\+\): \([^ ]\+\).*/\1 \2/p' | sort -u | while read -r n id; do
    [ -e "/proc/asound/card$n/usbid" ] && echo "$id"
  done | awk 'NF' | sort -u
}

SPK="${1:-}"
if [ -z "$SPK" ]; then
  mapfile -t cards < <(usb_playback_ids)
  case "${#cards[@]}" in
    0) echo ">> No USB speaker found in 'aplay -l'."
       echo "   Plug your USB speaker in and re-run, or pass its card id explicitly:"
       echo "      $(basename "$0") <CARD_ID>     (CARD_ID = the name after 'card N:' in 'aplay -l')"
       exit 0 ;;
    1) SPK="${cards[0]}" ; echo ">> Detected one USB speaker: $SPK" ;;
    *) echo ">> Multiple USB playback cards found: ${cards[*]}"
       echo "   Re-run naming the one you want:  $(basename "$0") <CARD_ID>"
       exit 0 ;;
  esac
fi

# Validate the chosen id is really a playback card (catches typos / a mic id).
if ! aplay -l 2>/dev/null | grep -q "^card [0-9]*: ${SPK} "; then
  echo "!! '$SPK' is not a playback card in 'aplay -l'. Check the name and retry." >&2
  exit 1
fi

# Preserve a hand-written ~/.asoundrc we didn't generate (so we never silently clobber the user's).
if [ -f "$ASOUND" ] && ! grep -qF "$MARKER" "$ASOUND"; then
  cp -f "$ASOUND" "$ASOUND.bak"
  echo "   (backed up your existing ~/.asoundrc -> ~/.asoundrc.bak)"
fi

cat > "$ASOUND" <<EOF
$MARKER
# Makes the USB speaker '$SPK' the system DEFAULT output, so the robot's VOICE (Piper -> aplay with no
# -D) comes out of it. Delete this file (or run scripts/cleanup_pi.sh) to restore the previous default.
pcm.!default { type plug; slave.pcm "hw:CARD=$SPK,DEV=0" }
ctl.!default { type hw; card $SPK }
EOF
echo ">> wrote ~/.asoundrc  (default output -> $SPK)"

# Set a sane volume + persist across reboots. The control name varies by device (PCM / Master / Speaker),
# and tiny USB speakers often expose NONE -- that's fine, the level is just fixed in hardware, not an error.
vol_ctl=""
for ctl in PCM Master Speaker; do
  if amixer -c "$SPK" sset "$ctl" 100% >/dev/null 2>&1; then vol_ctl="$ctl"; break; fi
done
if [ -n "$vol_ctl" ]; then
  sudo alsactl store >/dev/null 2>&1 || true
  echo "   volume set to 100% ('$vol_ctl') and persisted (alsactl store)"
else
  echo "   ('$SPK' exposes no volume control -- level is fixed in hardware; nothing to set)"
fi

# Write the matching device names straight into config/robot.env (by NAME, so a reboot/replug can't shift
# them) -- no more hand-editing. Idempotent: a re-run rewrites the SAME values and keeps each line's
# explanatory comment. (Hand-tuned one of these? A re-run re-detects and overwrites it.)
REPO="$(cd "$(dirname "$0")/.." && pwd)"
ENV="$REPO/config/robot.env"
set_kv() {   # set_kv KEY VALUE -- replace only KEY's VALUE in place; preserve any trailing "# comment"
  sed -i -E "s|^($1=)[^[:space:]#]*(.*)$|\1$2\2|" "$ENV"
}
mic_id="$(arecord -l 2>/dev/null | sed -n 's/^card \([0-9]\+\): \([^ ]\+\).*/\1 \2/p' | sort -u \
            | while read -r n id; do [ -e "/proc/asound/card$n/usbid" ] && echo "$id"; done | head -n1)"
echo
if [ -f "$ENV" ]; then
  set_kv ROBOT_SOUNDS_DEVICE "plughw:CARD=$SPK,DEV=0"
  echo ">> config/robot.env set:  ROBOT_SOUNDS_DEVICE=plughw:CARD=$SPK,DEV=0"
  if [ -n "${mic_id:-}" ]; then
    set_kv ROBOT_MIC "plughw:CARD=$mic_id,DEV=0"
    set_kv ROBOT_WAKEWORD_DEVICE "$mic_id"
    echo "                          ROBOT_MIC=plughw:CARD=$mic_id,DEV=0"
    echo "                          ROBOT_WAKEWORD_DEVICE=$mic_id"
  else
    echo "   (no USB mic detected -- left ROBOT_MIC as-is; set it from 'arecord -l' if voice input stays silent)"
  fi
else
  echo "   (config/robot.env not found -- couldn't set the audio device names)"
fi
echo
echo ">> Verify:  speaker-test -D default -t wav -l 1   (hear it from the speaker = the VOICE path is set)"
